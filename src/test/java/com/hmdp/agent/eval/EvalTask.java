package com.hmdp.agent.eval;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.stream.Stream;

/**
 * One row of the 50-task evaluation set, loaded from {@code eval/tasks/*.json}.
 *
 * <p>The set is data, not code: the JSON under {@code eval/tasks/} is the single source of truth and
 * is generated by {@code eval/gen_tasks.py} from the same shop catalogue {@link EvalWorld} serves,
 * so a task's compliant shop set cannot drift away from the world it is graded against.</p>
 *
 * <p>Every expectation here is <em>checkable</em>: it names shops, prices, distances, tool names and
 * argument bounds, never "the answer looks good". That is what keeps the judge a rule engine instead
 * of a second model.</p>
 *
 * @param id                       task id, e.g. {@code S01}
 * @param category                 the coverage bucket (single_constraint, multi_constraint, ...)
 * @param input                    the user's message
 * @param judgement                how this task is graded; see {@link EvalJudge}
 * @param world                    the canned world the task runs against
 * @param constraints              the hard constraints; empty when the task carries none
 * @param expectedTools            tools that must be called at least once
 * @param forbiddenTools           tools that must not be called at all
 * @param minToolCalls             per-tool minimum call counts, e.g. {@code search_nearby=2}
 * @param paramChecks              argument assertions on real tool calls
 * @param compliantShopIds         the ids that satisfy every hard constraint (derived from the world)
 * @param mustPresentShopIds       shops the answer must name
 * @param mustPresentCategories    categories that must each contribute at least one compliant shop
 * @param forbiddenShopIds         shops the answer must not name (filtered-out or off-scope)
 * @param minShops                 how many shops the answer must name (0 = do not check)
 * @param minCompliantNamed        how many compliant shops the answer must name (0 = do not check)
 * @param maxToolCalls             the most tool calls this task may issue
 * @param expectedVoucherTitles    voucher titles the answer must contain
 * @param expectVouchers           {@code TRUE} when vouchers exist and must be reported; {@code null}
 *                                 when the task does not care
 * @param forbiddenAnswerPhrases   phrases the answer must not contain (claiming an action not taken)
 * @param requiredAnswerPhrases    phrases the answer must contain (e.g. reporting "nothing found")
 * @param declaredRadiusMax        upper bound on the radius the model may declare for a vague request
 * @param declaredBudgetMax        upper bound on the budget the model may declare for a vague request
 * @param scriptedAnswer           the answer the scripted model emits
 * @param plan                     the tool calls the scripted model issues, in order
 * @param reason                   why this task is in the set (written into the report)
 */
record EvalTask(
        String id,
        String category,
        String input,
        String judgement,
        String world,
        List<Constraint> constraints,
        List<String> expectedTools,
        List<String> forbiddenTools,
        List<MinCalls> minToolCalls,
        List<ParamCheck> paramChecks,
        List<Long> compliantShopIds,
        List<Long> mustPresentShopIds,
        List<String> mustPresentCategories,
        List<Long> forbiddenShopIds,
        Integer minShops,
        Integer minCompliantNamed,
        Integer maxToolCalls,
        List<String> expectedVoucherTitles,
        Boolean expectVouchers,
        List<String> forbiddenAnswerPhrases,
        List<String> requiredAnswerPhrases,
        Integer declaredRadiusMax,
        Integer declaredBudgetMax,
        String scriptedAnswer,
        List<PlannedCall> plan,
        String reason) {

    /** Hard constraint kinds the judge understands. */
    static final String RADIUS = "radius";
    static final String BUDGET = "budget";
    static final String CATEGORY = "category";
    static final String SELF_RADIUS = "self_radius";
    static final String HAS_VOUCHER = "has_voucher";

    /** One hard constraint; {@code value} is the raw text from the task file. */
    record Constraint(String type, String value) {
    }

    /** A minimum call count for one tool. */
    record MinCalls(String tool, int count) {
    }

    /**
     * An argument assertion on real tool calls.
     *
     * @param tool      the tool name
     * @param path      the argument field
     * @param lte       upper bound (inclusive), or {@code null}
     * @param gte       lower bound (inclusive), or {@code null}
     * @param equals    the exact value as text, or {@code null}
     * @param allowed   accepted values as text; empty when unused
     * @param allCalls  {@code true} to assert on every call of that tool, not only the first
     */
    record ParamCheck(
            String tool, String path, Integer lte, Integer gte, String equals, List<String> allowed,
            boolean allCalls) {
    }

    /** One scripted tool call: the tool name and its argument object. */
    record PlannedCall(String tool, JsonNode args) {

        /** The arguments as the JSON text a model would stream. */
        String argsJson() {
            return args.toString();
        }
    }

    static final String JUDGE_SATISFY_ALL = "satisfy_all";
    static final String JUDGE_NO_SOLUTION = "no_solution";
    static final String JUDGE_REFUSE = "refuse";
    static final String JUDGE_CLARIFY = "clarify";

    /** @return {@code true} when the task has a constraint of that type. */
    boolean hasConstraint(String type) {
        return constraint(type) != null;
    }

    /** @return the first constraint of that type, or {@code null}. */
    Constraint constraint(String type) {
        for (Constraint constraint : constraints) {
            if (constraint.type().equals(type)) {
                return constraint;
            }
        }
        return null;
    }

    /** @return the numeric value of a radius/budget constraint, or {@code null} for a vague one. */
    Integer numberConstraint(String type) {
        Constraint constraint = constraint(type);
        if (constraint == null || constraint.value() == null) {
            return null;
        }
        try {
            return Integer.valueOf(constraint.value().trim());
        } catch (NumberFormatException notANumber) {
            return null;
        }
    }

    /** @return {@code true} when no tool should be called (chat, refusal). */
    boolean toolFree() {
        return expectedTools.isEmpty() && plan.isEmpty();
    }

    /** @return the tool-call ceiling, defaulting to the loop's own default. */
    int toolCallCeiling() {
        return maxToolCalls == null ? 12 : maxToolCalls;
    }

    /** @return how many shops the answer must name; 0 when the task does not check that. */
    int requiredShopCount() {
        if (minShops != null) {
            return minShops;
        }
        return mustPresentShopIds.size();
    }

    // -------------------------------------------------------------- loading

    private static final ObjectMapper MAPPER = new ObjectMapper();

    /** The directory holding the task set, relative to the build's working directory. */
    static final Path TASK_DIR = Path.of("eval", "tasks");

    /** Loads every {@code *.json} task file, sorted by file name so ids keep their declared order. */
    static List<EvalTask> loadAll() {
        return loadAll(TASK_DIR);
    }

    static List<EvalTask> loadAll(Path directory) {
        List<Path> files = new ArrayList<>();
        try (Stream<Path> entries = Files.list(directory)) {
            entries.filter(path -> path.getFileName().toString().endsWith(".json")).forEach(files::add);
        } catch (IOException broken) {
            throw new UncheckedIOException("无法读取任务集目录 " + directory.toAbsolutePath(), broken);
        }
        files.sort(Comparator.comparing(path -> path.getFileName().toString()));
        List<EvalTask> tasks = new ArrayList<>();
        for (Path file : files) {
            tasks.addAll(loadFile(file));
        }
        return List.copyOf(tasks);
    }

    static List<EvalTask> loadFile(Path file) {
        JsonNode root = readJson(file);
        String category = root.path("category").asText();
        List<EvalTask> tasks = new ArrayList<>();
        for (JsonNode node : root.path("tasks")) {
            tasks.add(fromJson(category, node));
        }
        return List.copyOf(tasks);
    }

    static JsonNode readJson(Path file) {
        try {
            return MAPPER.readTree(Files.readString(file, StandardCharsets.UTF_8));
        } catch (IOException broken) {
            throw new UncheckedIOException("无法解析任务文件 " + file.toAbsolutePath(), broken);
        }
    }

    /** Reads one JSON file into a task, applying the documented defaults. */
    static EvalTask fromJson(String category, JsonNode node) {
        List<Constraint> constraints = new ArrayList<>();
        for (JsonNode item : node.path("hardConstraints")) {
            constraints.add(new Constraint(item.path("type").asText(),
                    item.hasNonNull("value") ? item.path("value").asText() : null));
        }
        List<MinCalls> minCalls = new ArrayList<>();
        for (JsonNode item : node.path("minToolCalls")) {
            minCalls.add(new MinCalls(item.path("tool").asText(), item.path("count").asInt()));
        }
        List<ParamCheck> checks = new ArrayList<>();
        for (JsonNode item : node.path("paramChecks")) {
            checks.add(new ParamCheck(
                    item.path("tool").asText(),
                    item.path("path").asText(),
                    item.hasNonNull("lte") ? item.path("lte").asInt() : null,
                    item.hasNonNull("gte") ? item.path("gte").asInt() : null,
                    item.hasNonNull("equals") ? item.path("equals").asText() : null,
                    strings(item.path("in")),
                    item.path("allCalls").asBoolean(false)));
        }
        List<PlannedCall> plan = new ArrayList<>();
        for (JsonNode item : node.path("plan")) {
            plan.add(new PlannedCall(item.path("tool").asText(), item.path("args")));
        }
        return new EvalTask(
                node.path("id").asText(),
                category,
                node.path("input").asText(),
                node.path("judgement").asText(),
                node.path("world").asText("main"),
                List.copyOf(constraints),
                strings(node.path("expectedTools")),
                strings(node.path("forbiddenTools")),
                List.copyOf(minCalls),
                List.copyOf(checks),
                longs(node.path("compliantShopIds")),
                longs(node.path("mustPresentShopIds")),
                strings(node.path("mustPresentCategories")),
                longs(node.path("forbiddenShopIds")),
                nullableInt(node, "minShops"),
                nullableInt(node, "minCompliantNamed"),
                nullableInt(node, "maxToolCalls"),
                strings(node.path("expectedVoucherTitles")),
                node.hasNonNull("expectVouchers") ? node.path("expectVouchers").asBoolean() : null,
                strings(node.path("forbiddenAnswerPhrases")),
                strings(node.path("requiredAnswerPhrases")),
                nullableInt(node, "declaredRadiusMax"),
                nullableInt(node, "declaredBudgetMax"),
                node.hasNonNull("scriptedAnswer") ? node.path("scriptedAnswer").asText() : null,
                List.copyOf(plan),
                node.path("reason").asText());
    }

    private static Integer nullableInt(JsonNode node, String field) {
        JsonNode value = node.path(field);
        return value.isNumber() ? value.asInt() : null;
    }

    private static List<String> strings(JsonNode array) {
        List<String> values = new ArrayList<>();
        for (JsonNode item : array) {
            values.add(item.asText());
        }
        return List.copyOf(values);
    }

    private static List<Long> longs(JsonNode array) {
        List<Long> values = new ArrayList<>();
        for (JsonNode item : array) {
            values.add(item.asLong());
        }
        return List.copyOf(new LinkedHashSet<>(values));
    }
}
